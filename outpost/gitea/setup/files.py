"""What `gitea setup` writes on the Gitea server: app.ini, the systemd unit, and the token's scopes.

app.ini is written only once (the secrets in it are generated on the server); the unit is written
on every setup.
"""

# What the stored token may do. Uploads need write:package; the demo creates a repository, commits
# and sets a secret (write:repository, write:organization); runners are registered on the organisation.
# No write:admin and no write:user: a stolen secrets/gitea-token cannot take over the server.
TOKEN_SCOPES = "write:organization,write:repository,write:package,read:user,read:misc"

APP_INI = """; Generated by Outpost. Edit, then `systemctl restart gitea`.
APP_NAME = Outpost Gitea
RUN_USER = git
RUN_MODE = prod
WORK_PATH = /var/lib/gitea

[server]
PROTOCOL = https
DOMAIN = {name}
ROOT_URL = https://{name}/
HTTP_ADDR = 0.0.0.0
HTTP_PORT = 443
CERT_FILE = /etc/gitea/gitea.crt
KEY_FILE = /etc/gitea/gitea.key
START_SSH_SERVER = true
SSH_DOMAIN = {name}
SSH_PORT = 2222
SSH_LISTEN_PORT = 2222
LFS_START_SERVER = true
LFS_JWT_SECRET = __LFS_JWT_SECRET__
OFFLINE_MODE = true

[database]
DB_TYPE = sqlite3
PATH = /var/lib/gitea/data/gitea.db

[repository]
ROOT = /var/lib/gitea/data/repositories

[packages]
ENABLED = true
LIMIT_TOTAL_OWNER_SIZE = -1
LIMIT_SIZE_CONTAINER = -1
LIMIT_SIZE_DEBIAN = -1
LIMIT_SIZE_GENERIC = -1
LIMIT_SIZE_NPM = -1
LIMIT_SIZE_PYPI = -1

[actions]
ENABLED = true

[service]
DISABLE_REGISTRATION = true
REQUIRE_SIGNIN_VIEW = false

[security]
INSTALL_LOCK = true
SECRET_KEY = __SECRET_KEY__
INTERNAL_TOKEN = __INTERNAL_TOKEN__

[oauth2]
JWT_SECRET = __JWT_SECRET__

[log]
MODE = file
LEVEL = Info
ROOT_PATH = /var/lib/gitea/log
"""

UNIT = """[Unit]
Description=Gitea (installed by Outpost)
After=network.target

[Service]
Type=simple
User=git
Group=git
WorkingDirectory=/var/lib/gitea
ExecStart=/usr/local/bin/gitea web --config /etc/gitea/app.ini
Restart=always
RestartSec=2
Environment=USER=git HOME=/var/lib/gitea GITEA_WORK_DIR=/var/lib/gitea
AmbientCapabilities=CAP_NET_BIND_SERVICE
CapabilityBoundingSet=CAP_NET_BIND_SERVICE
NoNewPrivileges=true

[Install]
WantedBy=multi-user.target
"""
