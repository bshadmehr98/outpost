"""Install Gitea on its server over SSH. Idempotent: run it again after changing servers.yml.

What ends up on the server:
  /usr/local/bin/gitea                 the binary from the box
  /etc/gitea/app.ini                   config: HTTPS on 443, SQLite, packages on, registration off
  /etc/gitea/gitea.crt, gitea.key      certificate signed by your CA (pki/ca.crt)
  /var/lib/gitea/                      data, repositories, packages
  /etc/systemd/system/gitea.service    runs as user `git`
  /usr/local/sbin/outpost-egress       the server is sealed once Gitea is up

What ends up on your laptop:
  secrets/gitea-token                  the token Outpost uses (packages, organisation, repositories; not admin)
  secrets/gitea-admin-password         so you can log in to the web UI
  state/gitea.json                     name, ip, version

Upgrades: when versions.GITEA is newer than what runs on the server, setup takes a backup into
backups/ first, then replaces the binary; Gitea migrates its database on the next start.
"""

import secrets as pysecrets
import shlex
import time

from .. import hosts, pki, versions
from ..config import Servers
from ..infra import egress, hostsfile
from ..infra.egress import PROXY_USER
from ..ssh import Host
from ..workspace import Workspace
from .connect import connect
from .service import GITEA_CLI, installed_version, wait_for_gitea

# What the stored token may do. Uploads need write:package; the demo creates a repository, commits
# and sets a secret (write:repository, write:organization); runners are registered on the organisation.
# No write:admin and no write:user: a stolen secrets/gitea-token cannot take over the server.
TOKEN_SCOPES = "write:organization,write:repository,write:package,read:user,read:misc"

APP_INI = """; Generated by Outpost. Edit, then `systemctl restart gitea`.
APP_NAME = Outpost Gitea
RUN_USER = git
RUN_MODE = prod
WORK_PATH = /var/lib/gitea

[server]
PROTOCOL = https
DOMAIN = {name}
ROOT_URL = https://{name}/
HTTP_ADDR = 0.0.0.0
HTTP_PORT = 443
CERT_FILE = /etc/gitea/gitea.crt
KEY_FILE = /etc/gitea/gitea.key
START_SSH_SERVER = true
SSH_DOMAIN = {name}
SSH_PORT = 2222
SSH_LISTEN_PORT = 2222
LFS_START_SERVER = true
LFS_JWT_SECRET = __LFS_JWT_SECRET__
OFFLINE_MODE = true

[database]
DB_TYPE = sqlite3
PATH = /var/lib/gitea/data/gitea.db

[repository]
ROOT = /var/lib/gitea/data/repositories

[packages]
ENABLED = true
LIMIT_TOTAL_OWNER_SIZE = -1
LIMIT_SIZE_CONTAINER = -1
LIMIT_SIZE_DEBIAN = -1
LIMIT_SIZE_GENERIC = -1
LIMIT_SIZE_NPM = -1
LIMIT_SIZE_PYPI = -1

[actions]
ENABLED = true

[service]
DISABLE_REGISTRATION = true
REQUIRE_SIGNIN_VIEW = false

[security]
INSTALL_LOCK = true
SECRET_KEY = __SECRET_KEY__
INTERNAL_TOKEN = __INTERNAL_TOKEN__

[oauth2]
JWT_SECRET = __JWT_SECRET__

[log]
MODE = file
LEVEL = Info
ROOT_PATH = /var/lib/gitea/log
"""

UNIT = """[Unit]
Description=Gitea (installed by Outpost)
After=network.target

[Service]
Type=simple
User=git
Group=git
WorkingDirectory=/var/lib/gitea
ExecStart=/usr/local/bin/gitea web --config /etc/gitea/app.ini
Restart=always
RestartSec=2
Environment=USER=git HOME=/var/lib/gitea GITEA_WORK_DIR=/var/lib/gitea
AmbientCapabilities=CAP_NET_BIND_SERVICE
CapabilityBoundingSet=CAP_NET_BIND_SERVICE
NoNewPrivileges=true

[Install]
WantedBy=multi-user.target
"""

GITEA = GITEA_CLI


def setup(workspace: Workspace, servers: Servers, log=print) -> dict:  # noqa: C901 too complex; split into named steps in the refactor
    cfg = servers.gitea
    host = Host(cfg.host)
    binary = workspace.box_dir / "files" / "gitea" / versions.GITEA / "gitea"
    if not binary.exists():
        raise RuntimeError(f"{binary} is missing. Run `outpost fetch --only files` first.")

    log(f"==> [1/7] connecting to {cfg.host}")
    facts = host.facts()
    ip = cfg.ip or facts.get("ip")
    if not ip:
        raise RuntimeError("Could not detect the Gitea host's IP. Set gitea.ip in servers.yml.")
    want = versions.arch_names()["uname"]
    if facts.get("arch") and facts["arch"] != want:
        raise RuntimeError(
            f"[{cfg.host}] is {facts['arch']} but this platform is built for {want} (arch: {versions.ARCH} in servers.yml)."
        )
    log(f"[{cfg.host}] {facts.get('id', '?')} {facts.get('codename', '')}, Gitea will be https://{cfg.name} ({ip})")

    log("==> [2/7] certificates")
    pki.ensure_ca(workspace)
    cert, key = pki.ensure_gitea_cert(workspace, cfg.name, ip)

    log(f"==> [3/7] gitea {versions.GITEA} binary")
    installed = installed_version(host)
    if installed != versions.GITEA:
        if installed:
            from .backup import backup

            log(f"[{cfg.host}] gitea {installed} is installed; backing it up before upgrading to {versions.GITEA}")
            backup(workspace, servers, workspace.root / "backups", log=log, host=host)
        log(f"[{cfg.host}] uploading gitea {versions.GITEA} binary ({binary.stat().st_size // 1_000_000} MB)")
        host.run("systemctl stop gitea 2>/dev/null || true", raise_on_failure=True)
        host.put(binary, "/usr/local/bin/gitea", mode="0755")
    if not host.run("command -v git").ok:
        log(f"[{cfg.host}] git is not installed; trying the host's package manager")
        if (
            not host.run(
                "DEBIAN_FRONTEND=noninteractive apt-get install -y -qq git 2>&1 | tail -2 || dnf install -y git"
            ).ok
            or not host.run("command -v git").ok
        ):
            raise RuntimeError(
                f"[{cfg.host}] Gitea needs git. Install it once (apt-get install git), then rerun `outpost gitea setup`."
            )
    host.run(
        "id git >/dev/null 2>&1 || useradd --system --shell /bin/bash --home /var/lib/gitea --create-home git\n"
        "mkdir -p /var/lib/gitea/{custom,data,log} /etc/gitea\n"
        "chown -R git:git /var/lib/gitea && chmod 750 /var/lib/gitea\n",
        raise_on_failure=True,
    )
    host.write("/etc/gitea/gitea.crt", cert.read_text())
    host.write("/etc/gitea/gitea.key", key.read_text(), mode="0640")
    hostsfile.install(host, ip, cfg.name)  # now, and again at every boot

    log("==> [4/7] configuration and service")
    if not host.run("test -s /etc/gitea/app.ini").ok:
        log(f"[{cfg.host}] writing /etc/gitea/app.ini")
        host.write("/etc/gitea/app.ini", APP_INI.format(name=cfg.name), mode="0640")
        host.run(
            'sed -i "s|__SECRET_KEY__|$(/usr/local/bin/gitea generate secret SECRET_KEY)|" /etc/gitea/app.ini\n'
            'sed -i "s|__INTERNAL_TOKEN__|$(/usr/local/bin/gitea generate secret INTERNAL_TOKEN)|" /etc/gitea/app.ini\n'
            'sed -i "s|__JWT_SECRET__|$(/usr/local/bin/gitea generate secret JWT_SECRET)|" /etc/gitea/app.ini\n'
            'sed -i "s|__LFS_JWT_SECRET__|$(/usr/local/bin/gitea generate secret LFS_JWT_SECRET)|" /etc/gitea/app.ini\n',
            raise_on_failure=True,
        )
    # Gitea occasionally saves generated settings back into app.ini, so the git user owns it
    host.run(
        "chown git:git /etc/gitea/app.ini && chmod 640 /etc/gitea/app.ini && chown root:git /etc/gitea/gitea.key /etc/gitea/gitea.crt",
        raise_on_failure=True,
    )
    host.write("/etc/systemd/system/gitea.service", UNIT)
    host.run(
        "systemctl daemon-reload && systemctl enable gitea >/dev/null 2>&1; systemctl restart gitea",
        raise_on_failure=True,
    )
    wait_for_gitea(host)
    log(f"[{cfg.host}] gitea is answering on https://{cfg.name}")

    log("==> [5/7] admin user and token")
    password = workspace.read_secret("gitea-admin-password")
    users = host.run(f"{GITEA} admin user list --admin 2>/dev/null || true", raise_on_failure=True).stdout
    if cfg.user not in users.split():
        password = password or pysecrets.token_urlsafe(18)
        host.run(
            f"{GITEA} admin user create --admin --username {shlex.quote(cfg.user)} --password {shlex.quote(password)} "
            f"--email {shlex.quote(cfg.user + '@' + cfg.name)} --must-change-password=false",
            raise_on_failure=True,
        )
        workspace.write_secret("gitea-admin-password", password)
        log(f"[{cfg.host}] created admin user {cfg.user} (password in secrets/gitea-admin-password)")
    token = workspace.read_secret("gitea-token")
    if (
        token
        and host.run(
            f"curl -sk --max-time 5 -o /dev/null -w '%{{http_code}}' -H 'Authorization: token {token}' "
            "https://127.0.0.1/api/v1/user"
        ).stdout.strip()
        != "200"
    ):
        log(f"[{cfg.host}] this Gitea does not accept secrets/gitea-token (reinstalled?); making a new one")
        token = None
    if not token:
        token = (
            host.run(
                f"{GITEA} admin user generate-access-token --username {shlex.quote(cfg.user)} "
                f"--token-name outpost-{int(time.time())} --scopes {TOKEN_SCOPES} --raw",
                raise_on_failure=True,
            )
            .stdout.strip()
            .splitlines()[-1]
        )
        workspace.write_secret("gitea-token", token)
        log(f"[{cfg.host}] created API token (secrets/gitea-token; scopes {TOKEN_SCOPES})")

    workspace.write_state(
        "gitea",
        {"name": cfg.name, "ip": ip, "org": cfg.org, "user": cfg.user, "version": versions.GITEA, "host": cfg.host},
    )

    log(f"==> [6/7] organisation {cfg.org}")
    with connect(workspace, servers) as client:
        if client.ensure_org(cfg.org):
            log(f"[{cfg.host}] created organisation {cfg.org}")
        remote_version = client.version()
    log(f"[{cfg.host}] gitea {remote_version}, org {cfg.org}")

    log("==> [7/7] sealing the server")
    # when the egress proxy runs here (`outpost proxy setup`), its user keeps its one exception
    proxy_state = workspace.read_state("proxy") or {}
    proxy_here = bool(
        servers.egress_proxy and servers.egress_proxy.host == cfg.host and proxy_state.get("host") == cfg.host
    )
    egress.install(host, ip, cfg.allow, proxy_user=PROXY_USER if proxy_here else None)
    if proxy_here:
        log(f"[{cfg.host}] the egress proxy runs here: its user {PROXY_USER} keeps its exception (TCP 443 and 80)")
    log(f"[{cfg.host}] egress: {egress.seal(host, 'gitea setup')}")
    hosts.record(workspace, cfg.host, hosts.inspect(host))
    return {"name": cfg.name, "ip": ip, "version": remote_version}
